@app.route("/delete_post/<int:post_id>", methods=["POST"])
@login_required
def delete_post(post_id):
    con = get_db()

    post = con.execute("""
        SELECT image FROM posts
        WHERE id = ? AND user_id = ?
    """, (post_id, session["user_id"])).fetchone()

    if not post:
        con.close()
        return "Publication introuvable ou accès interdit.", 404

    try:
        # Supprimer d'abord les données liées à la publication.
        con.execute(
            "DELETE FROM comments WHERE post_id = ?",
            (post_id,)
        )

        con.execute(
            "DELETE FROM likes WHERE post_id = ?",
            (post_id,)
        )

        # La condition user_id protège encore la suppression.
        con.execute("""
            DELETE FROM posts
            WHERE id = ? AND user_id = ?
        """, (post_id, session["user_id"]))

        con.commit()

    except Exception:
        con.connection.rollback()
        con.close()
        raise

    con.close()

    # Supprimer la photo après validation de la transaction.
    if post["image"]:
        nom_image = os.path.basename(post["image"])
        chemin = os.path.join(UPLOAD_FOLDER, nom_image)

        if os.path.isfile(chemin):
            os.remove(chemin)

    return redirect(url_for("index"))


