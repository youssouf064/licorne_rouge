@app.route("/group/<int:group_id>/post", methods=["POST"])
@login_required
def create_group_post(group_id):
    user_id = session["user_id"]
    content = request.form.get("content", "").strip()
    image_file = request.files.get("image")

    if not content and (not image_file or not image_file.filename):
        return "Écris un message ou ajoute une photo.", 400

    if len(content) > 5000:
        return "Publication trop longue (maximum 5000 caractères).", 400

    con = get_db()

    try:
        group = con.execute("""
            SELECT id FROM social_groups
            WHERE id = ?
        """, (group_id,)).fetchone()

        if not group:
            return "Groupe introuvable.", 404

        membership = con.execute("""
            SELECT id FROM group_members
            WHERE group_id = ?
            AND user_id = ?
            AND status = 'approved'
        """, (group_id, user_id)).fetchone()

        if not membership:
            return "Tu dois être membre approuvé pour publier.", 403

        try:
            image = save_image(image_file)
        except Exception:
            return "Image invalide ou impossible à enregistrer.", 400

        if image_file and image_file.filename and not image:
            return "Format d'image non autorisé.", 400

        con.execute("""
            INSERT INTO group_posts (
                group_id, user_id, content, image, date
            )
            VALUES (?, ?, ?, ?, ?)
        """, (
            group_id,
            user_id,
            content,
            image,
            datetime.now().strftime("%d/%m/%Y %H:%M")
        ))

        con.commit()

        return redirect(url_for("group_detail", group_id=group_id))

    except Exception:
        con.connection.rollback()
        raise

    finally:
        con.close()



