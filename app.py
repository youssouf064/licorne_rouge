@app.route("/group-post/<int:post_id>/react", methods=["POST"])
@login_required
def react_to_group_post(post_id):
    user_id = session["user_id"]
    reaction = request.form.get("reaction", "like")

    allowed_reactions = ["like", "love", "haha", "wow"]

    if reaction not in allowed_reactions:
        return "Réaction invalide.", 400

    con = get_db()

    try:
        post = con.execute("""
            SELECT group_id
            FROM group_posts
            WHERE id = ?
        """, (post_id,)).fetchone()

        if not post:
            abort(404)

        membership = con.execute("""
            SELECT id
            FROM group_members
            WHERE group_id = ?
            AND user_id = ?
            AND status = 'approved'
        """, (post["group_id"], user_id)).fetchone()

        if not membership:
            return "Tu dois être membre approuvé pour réagir.", 403

        existing = con.execute("""
            SELECT id, reaction
            FROM group_post_reactions
            WHERE group_post_id = ?
            AND user_id = ?
        """, (post_id, user_id)).fetchone()

        if existing and existing["reaction"] == reaction:
            con.execute("""
                DELETE FROM group_post_reactions
                WHERE id = ?
            """, (existing["id"],))
        elif existing:
            con.execute("""
                UPDATE group_post_reactions
                SET reaction = ?, created_at = ?
                WHERE id = ?
            """, (
                reaction,
                datetime.now().strftime("%d/%m/%Y %H:%M"),
                existing["id"]
            ))
        else:
            con.execute("""
                INSERT INTO group_post_reactions (
                    group_post_id, user_id, reaction, created_at
                )
                VALUES (?, ?, ?, ?)
            """, (
                post_id,
                user_id,
                reaction,
                datetime.now().strftime("%d/%m/%Y %H:%M")
            ))

        con.commit()

        return redirect(url_for(
            "group_detail",
            group_id=post["group_id"]
        ))

    except Exception:
        con.connection.rollback()
        raise

    finally:
        con.close()


