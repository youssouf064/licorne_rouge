@app.route("/edit_post/<int:post_id>", methods=["GET", "POST"])
@login_required
def edit_post(post_id):
    con = get_db()

    post = con.execute("""
        SELECT * FROM posts
        WHERE id = ? AND user_id = ?
    """, (post_id, session["user_id"])).fetchone()

    if not post:
        con.close()
        return "Publication introuvable ou accès interdit.", 404

    if request.method == "POST":
        content = request.form.get("content", "").strip()
        uploaded_file = request.files.get("image")
        new_image = None

        if uploaded_file and uploaded_file.filename:
            try:
                new_image = save_image(uploaded_file)
            except Exception:
                con.close()
                return "Image invalide ou trop volumineuse.", 400

            if not new_image:
                con.close()
                return "Format d'image non autorisé.", 400

        image = new_image if new_image else post["image"]

        if not content and not image:
            con.close()
            return "La publication doit contenir un texte ou une image.", 400

        try:
            con.execute("""
                UPDATE posts
                SET content = ?, image = ?
                WHERE id = ? AND user_id = ?
            """, (content, image, post_id, session["user_id"]))

            con.commit()
        except Exception:
            con.connection.rollback()
            con.close()

            if new_image:
                chemin = os.path.join(UPLOAD_FOLDER, new_image)
                if os.path.isfile(chemin):
                    os.remove(chemin)

            raise

        con.close()

        # Supprimer l'ancienne photo seulement après la mise à jour réussie.
        if new_image and post["image"]:
            ancien_nom = os.path.basename(post["image"])
            ancien_chemin = os.path.join(UPLOAD_FOLDER, ancien_nom)

            if os.path.isfile(ancien_chemin):
                os.remove(ancien_chemin)

        return redirect(url_for("index"))

    con.close()
    return render_template("edit_post.html", post=post)


