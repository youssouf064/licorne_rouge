class DBConnection:
    """Adaptateur compatible avec les anciennes routes Flask."""

    def __init__(self, connection, pool=None):
        self.connection = connection
        self.pool = pool
        self.closed = False

    def execute(self, sql, params=()):
        sql = sql.replace("?", "%s")
        return self.connection.execute(sql, params)

    def commit(self):
        self.connection.commit()

    def close(self):
        if self.closed:
            return

        self.closed = True

        if self.pool is not None:
            self.pool.putconn(self.connection)
        else:
            self.connection.close()


def get_db():
    global _db_pool

    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        raise RuntimeError("La variable DATABASE_URL n'est pas définie.")

    if _db_pool is None:
        with _db_pool_lock:
            if _db_pool is None:
                _db_pool = ConnectionPool(
                    conninfo=database_url,
                    min_size=1,
                    max_size=5,
                    kwargs={
                        "sslmode": "require",
                        "row_factory": dict_row
                    },
                    open=True
                )

    connection = _db_pool.getconn()
    return DBConnection(connection, _db_pool)


def redirect_back(default_endpoint="index", **values):
    """Revient à la page précédente, seulement si elle est sur notre site."""
    ref = request.referrer
    if ref and urlparse(ref).netloc == request.host:
        return redirect(ref)
    return redirect(url_for(default_endpoint, **values))


@app.context_processor
def inject_unread_counts():
    if "user_id" not in session:
        return {
            "unread_count": 0,
            "unread_messages": 0
        }

    con = get_db()

    try:
        counts = con.execute("""
            SELECT
                (
                    SELECT COUNT(*)
                    FROM notifications
                    WHERE user_id = ? AND is_read = 0
                ) AS unread_count,
                (
                    SELECT COUNT(*)
                    FROM messages
                    WHERE receiver_id = ? AND is_read = 0
                ) AS unread_messages
        """, (
            session["user_id"],
            session["user_id"]
        )).fetchone()

        unread_count = counts["unread_count"]
        unread_messages = counts["unread_messages"]

    except psycopg.Error:
        unread_count = 0
        unread_messages = 0

    finally:
        con.close()

    return {
        "unread_count": unread_count,
        "unread_messages": unread_messages
    }


