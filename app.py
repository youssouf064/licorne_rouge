@app.route("/group/<int:group_id>/leave", methods=["POST"])
@login_required
def leave_group(group_id):
    user_id = session["user_id"]
    con = get_db()

    try:
        group = con.execute("""
            SELECT id, owner_id
            FROM social_groups
            WHERE id = ?
        """, (group_id,)).fetchone()

        if not group:
            abort(404)

        if group["owner_id"] == user_id:
            return "L'administrateur propriétaire ne peut pas quitter son groupe.", 403

        con.execute("""
            DELETE FROM group_members
            WHERE group_id = ? AND user_id = ?
        """, (group_id, user_id))

        con.commit()

        return redirect(url_for(
            "group_detail",
            group_id=group_id
        ))

    finally:
        con.close()


